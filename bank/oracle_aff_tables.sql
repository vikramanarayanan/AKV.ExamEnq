-- Start after last PHP/MySQL bank uid 1002570208
-- Bank UID is always exactly 10 digits (1000000000 to 9999999999)
CREATE SEQUENCE SEQ_ONLINE_ROLL_AFF
  START WITH 1002570209
  INCREMENT BY 1
  MINVALUE 1000000000
  MAXVALUE 9999999999
  NOCACHE
  NOCYCLE;

