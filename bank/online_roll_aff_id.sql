-- Match ONLINE_ROLL_AFF.ID to ROLL.ID (VARCHAR2(100)) and copy existing values.

ALTER TABLE ONLINE_ROLL_AFF ADD ID2 VARCHAR2(100);

UPDATE ONLINE_ROLL_AFF a
   SET a.ID2 = (
         SELECT r.ID
           FROM ROLL r
          WHERE (r.REGNO = a.REGNO OR r.ROLLNO = a.ROLLNO)
            AND ROWNUM = 1
       );

ALTER TABLE ONLINE_ROLL_AFF DROP COLUMN ID;
ALTER TABLE ONLINE_ROLL_AFF RENAME COLUMN ID2 TO ID;

COMMIT;
EXIT;
