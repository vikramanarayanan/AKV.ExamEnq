-- Current exam-fee year prefix (first 3 characters of ONLINE_ROLL_AFF.REFNO).
-- Change this row when the year code changes (example: N26 -> N27).

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE EAZYPAY_YEAROFEXAM CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE EAZYPAY_YEAROFEXAM (
  MTHYR         CHAR(3)     NOT NULL,
  SHOWPAYMENT   NUMBER(1)   DEFAULT 1 NOT NULL,
  FINE          NUMBER(4)   DEFAULT 0 NOT NULL
);

INSERT INTO EAZYPAY_YEAROFEXAM (MTHYR, SHOWPAYMENT, FINE) VALUES ('N26', 1, 0);
COMMIT;
EXIT;
